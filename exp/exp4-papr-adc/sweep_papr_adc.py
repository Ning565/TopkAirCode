def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--device", default="cuda:3")
    parser.add_argument("--seed", type=int, default=2026)
    parser.add_argument("--rounds", type=int, default=200)
    parser.add_argument("--eval-every", type=int, default=5)
    parser.add_argument("--ratios", default="topk=0.15,randk=0.65,full=1.0")
    parser.add_argument("--gammas", default="0.8,1.0,1.1,1.2,1.3,1.5,2.0")
    parser.add_argument("--epsilon", type=float, default=3e8)
    parser.add_argument("--sigma0", type=float, default=0.03)
    parser.add_argument("--p-max", type=float, default=2.5e3)
    parser.add_argument("--adc-backoff-gamma", type=float, default=1.2)
    parser.add_argument("--element-clip", type=float, default=0.02)
    parser.add_argument("--error-feedback-methods", default="topk")
    parser.add_argument("--randk-mask-mode", choices=("common", "independent"), default="common")
    parser.add_argument("--lr-femnist", type=float, default=0.05)
    parser.add_argument("--lr-decay", type=float, default=0.992)
    parser.add_argument("--min-lr", type=float, default=0.005)
    parser.add_argument("--optimizer-momentum", type=float, default=0.9)
    parser.add_argument("--optimizer-weight-decay", type=float, default=1e-4)
    parser.add_argument("--output-dir", default="logs/experiments/exp4-papr-adc/papr_adc_sweep")
    args = parser.parse_args()

    if args.device.startswith("cuda") and not torch.cuda.is_available():
        args.device = "cpu"

    out_dir = Path(args.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    ratios = parse_ratios(args.ratios)
    gammas = parse_floats(args.gammas)
    base_cfg = Config(
        seed=args.seed,
        device=args.device,
        output_dir=str(out_dir),
        datasets=("femnist",),
        methods=METHOD_ORDER,
        rounds=args.rounds,
        eval_every=args.eval_every,
        lr_femnist=args.lr_femnist,
        lr_decay=args.lr_decay,
        min_lr=args.min_lr,
        optimizer_momentum=args.optimizer_momentum,
        optimizer_weight_decay=args.optimizer_weight_decay,
        epsilon=args.epsilon,
        sigma0=args.sigma0,
        p_max=args.p_max,
        adc_backoff_gamma=args.adc_backoff_gamma,
        element_clip=args.element_clip,
        error_feedback_methods=tuple(x.strip() for x in args.error_feedback_methods.split(",") if x.strip()),
        randk_mask_mode=args.randk_mask_mode,
    )
    with (out_dir / "config.json").open("w", encoding="utf-8") as handle:
        json.dump({"args": vars(args), "config": asdict(base_cfg)}, handle, indent=2, ensure_ascii=False)

    all_papr, all_gamma, all_round, all_eval = [], [], [], []
    for method in METHOD_ORDER:
        papr_rows, gamma_rows, round_rows, eval_rows = run_method(args, base_cfg, method, ratios[method], gammas)
        all_papr.extend(papr_rows)
        all_gamma.extend(gamma_rows)
        all_round.extend(round_rows)
        all_eval.extend(eval_rows)

    gamma_summary = aggregate_gamma(all_gamma)
    method_summary = aggregate_round(all_round, all_papr, gamma_summary, args.adc_backoff_gamma)
    stress_summary = add_resource_weighted_stress(gamma_summary, method_summary)
    write_csv(out_dir / "papr_samples.csv", all_papr)
    write_csv(out_dir / "gamma_round_metrics.csv", all_gamma)
    write_csv(out_dir / "gamma_summary.csv", gamma_summary)
    write_csv(out_dir / "resource_weighted_adc_stress.csv", stress_summary)
    write_csv(out_dir / "round_structure_metrics.csv", all_round)
    write_csv(out_dir / "eval_accuracy.csv", all_eval)
    write_csv(out_dir / "method_summary.csv", method_summary)
    plot_papr_ccdf(all_papr, out_dir)
    plot_gamma(gamma_summary, out_dir)
    plot_resource_weighted_gamma(stress_summary, out_dir)
    plot_support_stress(method_summary, out_dir)
    write_markdown(out_dir / "summary.md", args, method_summary)


if __name__ == "__main__":
    main()
