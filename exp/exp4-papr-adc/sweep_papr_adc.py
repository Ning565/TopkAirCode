def plot_support_stress(method_summary: list[dict[str, Any]], out_dir: Path) -> None:
    metrics = [
        ("effective_tx_ratio", "Effective transmitted coordinate ratio", "exp4_effective_tx_ratio.png"),
        ("active_overlap_mean", "Mean active-client overlap", "exp4_support_overlap_mean.png"),
    ]
    for key, ylabel, filename in metrics:
        labels = [method_label(row["method"]) for row in method_summary]
        values = [row[key] for row in method_summary]
        colors = [COLORS[row["method"]] for row in method_summary]
        plt.figure(figsize=(6.6, 4.4))
        plt.bar(labels, values, color=colors, width=0.58)
        plt.ylabel(ylabel)
        plt.grid(True, axis="y", linestyle="--", alpha=0.4)
        plt.tight_layout()
        plt.savefig(out_dir / filename, dpi=260)
        plt.close()


